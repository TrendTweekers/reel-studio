export const STRINGS: Record<Lang, Record<StrKey, string>> = { en, pl };

export const defaultLang = (): Lang => {
  try {
    const saved = localStorage.getItem('reel-studio-lang');
    if (saved === 'en' || saved === 'pl') return saved;
  } catch {
    /* ignore */
  }
  // English is the standard language; Polish is one click away and remembered.
  return 'en';
};

export type T = (key: StrKey) => string;

// Fill {name} placeholders.
export const fmt = (str: string, vars: Record<string, string | number>) => str.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));

// Numbers the way each language writes them: 4.7 in English, 4,7 in Polish.
export const num = (n: number, lang: Lang, digits = 1) =>
  n.toLocaleString(lang === 'pl' ? 'pl-PL' : 'en-US', { minimumFractionDigits: 0, maximumFractionDigits: digits });
export const numFixed = (n: number, lang: Lang, digits = 1) =>
  n.toLocaleString(lang === 'pl' ? 'pl-PL' : 'en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits });
// Plural forms: English one/many; Polish 1 efekt, 2-4 efekty, 5+ efektów (12-14 too).
export const plural = (n: number, lang: Lang, t: T, base: 'pause' | 'effect' | 'retake' | 'chapter') => {
  const a = Math.abs(n);
  const form = a === 1 ? 'one' : lang === 'pl' && a % 10 >= 2 && a % 10 <= 4 && !(a % 100 >= 12 && a % 100 <= 14) ? 'few' : 'many';
  return `${num(n, lang, 0)} ${t(`${base}_${form}` as StrKey)}`;
};

// Server error codes -> plain words. Unknown codes fall back to the server text.
const ERR_CODES = [
  'no_audio', 'bad_file', 'not_logged_in', 'claude_missing', 'stopped', 'render_failed', 'picture_missing',
  'upload_incomplete', 'no_internet', 'disk_full', 'no_speech', 'tool_missing', 'parent_missing', 'unknown', 'ask_failed', 'busy',
] as const;
export const errText = (t: T, code: string | null | undefined, text?: string | null) =>
  code && (ERR_CODES as readonly string[]).includes(code) ? t(`err_${code}` as StrKey) : text ?? '';

export const sfxLabel = (t: T, name: string) => t(`sfx_${name.replace(/-/g, '_')}` as StrKey) || name;

